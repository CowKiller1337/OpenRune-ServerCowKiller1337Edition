    val locIds: Set<Int> = obstacles.flatMap { it.locs.asIterable() }.toSet()

    fun findObstacle(locId: Int, coords: CoordGrid): AgilityObstacle? =
        obstacles.firstOrNull { obstacle ->
            locId in obstacle.locs && (obstacle.locCoords.isEmpty() || coords in obstacle.locCoords)
        }

    private fun seq(id: Int): String =
        RSCM.getReverseMapping(RSCMType.SEQ, id) ?: error("Missing agility seq: $id")

