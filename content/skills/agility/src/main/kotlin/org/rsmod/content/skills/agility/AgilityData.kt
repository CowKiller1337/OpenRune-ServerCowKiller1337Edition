internal data class AgilityCourse(
    val key: String,
    val name: String,
    val obstacleCount: Int,
    val lapXp: Double,
    val stepAttr: AttributeKey<Int>,
    val lapsAttr: AttributeKey<Int>,
)

internal data class AgilityObstacle(
    val course: AgilityCourse,
    val step: Int,
    val locs: IntArray,
    val locCoords: Set<CoordGrid> = emptySet(),
    val level: Int,
    val xp: Double,
    val start: CoordGrid,
    val end: CoordGrid,
    val path: List<CoordGrid> = emptyList(),
    val anim: String?,
    val animReplayInterval: Int? = null,
    val waitForArrival: Boolean = true,
    val delay: Int,
    val exactMoveDelay: Int,
    val faceDir: Int,
    val movement: AgilityMovement,
)

internal enum class AgilityMovement {
    ExactMove,
    StraightWalk,
    BalanceWalk,
    TelejumpAfterDelay,
}

